/* Бутонът „📖 Инструкция" на началния екран — вижда се от офисните акаунти
   (цеховите имат своите екрани). Поздравният банер за Деси е в app.js. */
function sysGuideBtnApply() {
  const b = document.getElementById("btn-julia");
  if (!b) return;
  const ok = typeof MY_ACCESS !== "undefined" && MY_ACCESS && MY_ACCESS.isAdmin && !MY_ACCESS.production;
  b.style.display = ok ? "" : "none";
}
(function sysGuideBtnInit() {
  const b = document.getElementById("btn-julia");
  if (!b) return;
  b.addEventListener("click", async () => {
    try { if (typeof openErp === "function") await openErp(); } catch (e) {}
    if (typeof erpSetTab === "function") erpSetTab("sysguide");
  });
})();
