function openTanyaGuide() {
  const modal = document.getElementById("tanya-modal");
  if (!modal) return;
  const box = document.getElementById("tanya-body");
  if (box && !box.dataset.filled) { box.innerHTML = `<div style="max-width:1000px;margin:0 auto;zoom:1.1">${tanyaGuideHtml()}</div>`; box.dataset.filled = "1"; }
  modal.hidden = false;
}

/* ⤓ PDF: печатен прозорец → в диалога избираш „Запази като PDF" и я пращаш по мейла. */
function tanyaGuidePdf() {
  const w = window.open("", "_blank");
  if (!w) { alert("Браузърът блокира прозореца — разреши popups."); return; }
  const today = new Date().toLocaleDateString("bg-BG");
  w.document.write(`<!doctype html><html><head><meta charset="utf-8"><title>Упътване — Таня Петкова · Данко Системс</title><style>
    body{font-family:Arial,Segoe UI,sans-serif;margin:28px;color:#111}
    h1{font-size:22px;margin:0 0 2px} .sub{color:#555;font-size:13px;margin-bottom:14px}
    h4{font-size:16px;margin:18px 0 6px;border-bottom:2px solid #1e3a8a;padding-bottom:3px;color:#1e3a8a}
    .hint{color:#444;font-size:13px} ol{font-size:13.5px} b{color:#000}
    div[style*="flex:0 0 175px"]{background:#eef2ff !important;-webkit-print-color-adjust:exact}
    .noprint{position:fixed;top:8px;right:8px;padding:8px 16px}
    @media print{.noprint{display:none}}
  </style></head><body>
    <h1>👩‍💼 Упътване за работа със СИСТЕМАТА — Таня Петкова</h1>
    <div class="sub">Офис акаунт office@dankosystems.com · Данко Системс · ${today}</div>
    ${tanyaGuideHtml()}
    <button class="noprint" onclick="window.print()">🖨 Печат / Запази като PDF</button>
  </body></html>`);
  w.document.close();
  setTimeout(() => { try { w.print(); } catch (e) {} }, 500);
}

(function tanyaInit() {
  const btn = document.getElementById("btn-tanya");
  if (btn) btn.addEventListener("click", openTanyaGuide);
  const cls = document.getElementById("tanya-close");
  if (cls) cls.addEventListener("click", () => { document.getElementById("tanya-modal").hidden = true; });
  const pdf = document.getElementById("tanya-pdf");
  if (pdf) pdf.addEventListener("click", tanyaGuidePdf);
})();
