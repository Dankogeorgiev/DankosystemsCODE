function tgRow(icon, what) {
  const cap = s => String(s).replace(/^([а-яa-z])/, m => m.toUpperCase());
  return `<div style="display:flex;gap:14px;padding:9px 10px;border-bottom:1px dashed #e2e8f0;font-size:14.5px;line-height:1.55;align-items:flex-start">
    <div style="flex:0 0 175px;font-weight:700;background:#eef2ff;border:1px solid #c7d2fe;border-radius:8px;padding:5px 9px;text-align:center;font-size:13.5px">${icon}</div>
    <div style="padding-top:4px">${cap(what)}</div></div>`;
}
function tgSec(t) { return `<h4 class="erp-group-head" style="margin-top:16px">${t}</h4>`; }

