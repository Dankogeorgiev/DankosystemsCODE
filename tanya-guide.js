function openTanyaGuide() {
  const modal = document.getElementById("tanya-modal");
  if (!modal) return;
  const box = document.getElementById("tanya-body");
  if (box && !box.dataset.filled) { box.innerHTML = `<div style="max-width:1000px;margin:0 auto;zoom:1.1">${tanyaGuideHtml()}</div>`; box.dataset.filled = "1"; }
  modal.hidden = false;
}

