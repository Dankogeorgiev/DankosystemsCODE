function infoFmtDate(iso) {
  const p = String(iso || "").split("-");
  return p.length === 3 ? `${p[2]}.${p[1]}.${p[0]}` : iso;
}
function infoRender() {
  const box = document.getElementById("info-list");
  if (!box) return;
  const esc = (typeof escapeHtml === "function") ? escapeHtml : (s => String(s));
  const news = (window.SYSTEM_NEWS || []).slice()
    .sort((a, b) => String(b.d).localeCompare(String(a.d)));
  let lastD = "";
  box.innerHTML = news.map(n => {
    const head = n.d !== lastD ? `<div class="info-date">${infoFmtDate(n.d)}</div>` : "";
    lastD = n.d;
    return `${head}<div class="info-item">${esc(n.t)}</div>`;
  }).join("") || `<p class="erp-muted">Още няма записи.</p>`;
}
function infoInit() {
  const btn = document.getElementById("btn-info");
  const modal = document.getElementById("info-modal");
  if (!btn || !modal) return;
  btn.addEventListener("click", () => { modal.hidden = false; infoRender(); });
  const cls = document.getElementById("info-close");
  if (cls) cls.addEventListener("click", () => { modal.hidden = true; });
}
infoInit();
